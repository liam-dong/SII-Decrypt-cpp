/* ==========================================================================
 *  Round constants (Rcon[i] = x^{i-1} in GF(2^8))
 * ========================================================================== */

static const uint8_t rcon[11] = {
    0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1B, 0x36
};

/* ==========================================================================
 *  Galois Field (2^8) multiplication
 *  Reduction polynomial: x^8 + x^4 + x^3 + x + 1  (0x11B)
 * ========================================================================== */

static uint8_t gmul(uint8_t a, uint8_t b)
{
    uint8_t p = 0;
    for (int i = 0; i < 8; ++i) {
        if (b & 1)
            p ^= a;
        uint8_t hi = a & 0x80;
        a <<= 1;
        if (hi)
            a ^= 0x1B;   /* reduction polynomial */
        b >>= 1;
    }
    return p;
}

/* ==========================================================================
 *  Key Expansion — AES-256
 *
 *  Produces 60 words (15 round keys of 4 words each).
 *    Nk = 8 (256-bit key in 32-bit words)
 *    Nr = 14 (rounds)
 *    expanded keys = 4 * (Nr + 1) = 60 words = 240 bytes
 * ========================================================================== */

static void key_expansion(const uint8_t* key, uint8_t* w)
{
    /* w[0..31] = key */
    memcpy(w, key, AES256_KEY_SIZE);

    for (int i = 8; i < 60; ++i) {
        /* w[i*4 .. i*4+3] */
        uint8_t temp[4];
        memcpy(temp, w + (i - 1) * 4, 4);

        if (i % 8 == 0) {
            /* RotWord */
            uint8_t t = temp[0];
            temp[0] = temp[1];
            temp[1] = temp[2];
            temp[2] = temp[3];
            temp[3] = t;
            /* SubWord */
            temp[0] = sbox[temp[0]];
            temp[1] = sbox[temp[1]];
            temp[2] = sbox[temp[2]];
            temp[3] = sbox[temp[3]];
            /* Xor Rcon */
            temp[0] ^= rcon[i / 8];
        } else if (i % 8 == 4) {
            /* SubWord only (AES-256 specific) */
            temp[0] = sbox[temp[0]];
            temp[1] = sbox[temp[1]];
            temp[2] = sbox[temp[2]];
            temp[3] = sbox[temp[3]];
        }

        /* w[i] = w[i-8] xor temp */
        for (int j = 0; j < 4; ++j)
            w[i * 4 + j] = w[(i - 8) * 4 + j] ^ temp[j];
    }
}

/* ==========================================================================
 *  InvShiftRows
 * ========================================================================== */

static void inv_shift_rows(uint8_t* state)
{
    uint8_t tmp;

    /* Row 0: no shift */

    /* Row 1: rotate right by 1 */
    tmp = state[13];
    state[13] = state[9];
    state[9]  = state[5];
    state[5]  = state[1];
    state[1]  = tmp;

    /* Row 2: rotate right by 2 */
    tmp = state[10];
    state[10] = state[2];
    state[2]  = tmp;
    tmp = state[14];
    state[14] = state[6];
    state[6]  = tmp;

    /* Row 3: rotate right by 3 (same as left by 1) */
    tmp = state[3];
    state[3]  = state[7];
    state[7]  = state[11];
    state[11] = state[15];
    state[15] = tmp;
}

/* ==========================================================================
 *  InvSubBytes
 * ========================================================================== */

static void inv_sub_bytes(uint8_t* state)
{
    for (int i = 0; i < 16; ++i)
        state[i] = inv_sbox[state[i]];
}

/* ==========================================================================
 *  InvMixColumns
 *
 *  Each column is multiplied by the inverse MDS matrix:
 *    [0E 0B 0D 09]
 *    [09 0E 0B 0D]
 *    [0D 09 0E 0B]
 *    [0B 0D 09 0E]
 * ========================================================================== */

static void inv_mix_columns(uint8_t* state)
{
    for (int c = 0; c < 4; ++c) {
        int i = c * 4;
        uint8_t s0 = state[i], s1 = state[i+1], s2 = state[i+2], s3 = state[i+3];

        state[i]   = gmul(0x0E, s0) ^ gmul(0x0B, s1) ^ gmul(0x0D, s2) ^ gmul(0x09, s3);
        state[i+1] = gmul(0x09, s0) ^ gmul(0x0E, s1) ^ gmul(0x0B, s2) ^ gmul(0x0D, s3);
        state[i+2] = gmul(0x0D, s0) ^ gmul(0x09, s1) ^ gmul(0x0E, s2) ^ gmul(0x0B, s3);
        state[i+3] = gmul(0x0B, s0) ^ gmul(0x0D, s1) ^ gmul(0x09, s2) ^ gmul(0x0E, s3);
    }
}

/* ==========================================================================
 *  AddRoundKey
 * ========================================================================== */

static void add_round_key(uint8_t* state, const uint8_t* round_key)
{
    for (int i = 0; i < 16; ++i)
        state[i] ^= round_key[i];
}

/* ==========================================================================
 *  Decrypt a single 128-bit block
 * ========================================================================== */

static void decrypt_block(const uint8_t* input, uint8_t* output,
                          const uint8_t* w /* 240 bytes of expanded keys */)
{
    uint8_t state[16];
    memcpy(state, input, 16);

    /* Initial round — AddRoundKey with last round key (round 14) */
    add_round_key(state, w + 14 * 16);

    /* Rounds 13 down to 1 */
    for (int r = 13; r >= 1; --r) {
        inv_shift_rows(state);
        inv_sub_bytes(state);
        add_round_key(state, w + r * 16);
        inv_mix_columns(state);
    }

    /* Final round (round 0) — no InvMixColumns */
    inv_shift_rows(state);
    inv_sub_bytes(state);
    add_round_key(state, w + 0 * 16);

    memcpy(output, state, 16);
}

/* ==========================================================================
 *  Public API
 * ========================================================================== */

int aes256_decrypt_cbc(const uint8_t* key, const uint8_t* iv,
                       const uint8_t* input, size_t len,
                       uint8_t* output, size_t* out_len)
{
    if (!key || !iv || !input || !output || !out_len)
        return -1;
    if (len == 0 || (len % AES256_BLOCK_SIZE) != 0)
        return -1;

    /* Expand key */
    uint8_t w[240];
    key_expansion(key, w);

    /* CBC decrypt */
    uint8_t prev[16];
    memcpy(prev, iv, 16);

    for (size_t off = 0; off < len; off += AES256_BLOCK_SIZE) {
        uint8_t decrypted[16];
        decrypt_block(input + off, decrypted, w);

        /* XOR with previous ciphertext (or IV for first block) */
        for (int i = 0; i < 16; ++i)
            output[off + i] = decrypted[i] ^ prev[i];

        /* Save current ciphertext block for next XOR */
        memcpy(prev, input + off, 16);
    }

    /* Remove PKCS#7 padding */
    uint8_t pad = output[len - 1];
    if (pad == 0 || pad > 16)
        return -1;

    /* Verify all padding bytes */
    for (uint8_t i = 0; i < pad; ++i) {
        if (output[len - 1 - i] != pad)
            return -1;
    }

    *out_len = len - pad;
    return 0;
}
